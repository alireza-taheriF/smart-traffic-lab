#!/usr/bin/env node
/* Builds docs/BENCHMARKS.md from results/*.json */
const fs = require('fs'), path = require('path');
const R = path.join(__dirname, '..', 'results');
const NAME = { cross: 'Cross (4-way)', tee: 'T-junction', corridor: 'Corridor (3 intersections)', grid: 'Grid 2x2' };
const load = (n) => JSON.parse(fs.readFileSync(path.join(R, n + '.json'), 'utf8'));
const f0 = (x) => x.toFixed(0), f1 = (x) => x.toFixed(1), pc = (x) => (x * 100).toFixed(0) + '%';
let md = '# Benchmarks\n\nGenerated by `npm run report` from `results/*.json` (do not edit by hand).\n\n' +
  '* **Load** = vehicles/hour on each main entry (east/west); north/south entries get 65% of that.\n' +
  '* **Delay** = mean seconds a vehicle spends *stopped*, **including vehicles still waiting when the run ends** (no survivor bias).\n' +
  '* Both controllers see exactly the same random vehicles (paired comparison). 5 seeds (101-105, never used for tuning), 300 s warm-up + 1500 s measured.\n' +
  '* "Fixed" = the baseline that mimics common Iranian practice (fixed cycle, 35 s through / 12 s left arrow, countdown timers).\n\n';
for (const mode of ['protected', 'permissive']) {
  md += `## Left turns: ${mode === 'protected' ? 'protected (dedicated left lane + left arrow, as in Mashhad)' : 'permissive (shared lane, yield to oncoming)'}\n\n`;
  md += '| Layout | Load | Fixed delay (s) | Smart delay (s) | **Improvement** | Queue fixed → smart | Max wait fixed → smart (s) | Throughput veh/h fixed → smart | Conflicts |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|\n';
  for (const s of ['cross', 'tee', 'corridor', 'grid']) {
    for (const r of load(`${s}-${mode}`)) {
      md += `| ${NAME[s]} | ${r.rate} | ${f1(r.fixed.delayAll)} | ${f1(r.smart.delayAll)} | **${pc(r.gainAll)}** ±${f0(r.gainAllSd * 100)} | ${f0(r.fixed.queue)} → ${f0(r.smart.queue)} | ${f0(r.fixed.maxWait)} → ${f0(r.smart.maxWait)} | ${f0(r.fixed.thr)} → ${f0(r.smart.thr)} | ${r.conflicts} |\n`;
    }
  }
  md += '\n';
}
const ab = load('ablation');
md += '## Ablation (cross, protected left): what each idea is worth\n\n| Variant | ' + ab.rates.map(r => `load ${r}`).join(' | ') + ' |\n|---|' + ab.rates.map(() => '---:').join('|') + '|\n';
for (const row of ab.rows) md += `| ${row.name} | ${row.gains.map(pc).join(' | ')} |\n`;
md += '\n## Emergency vehicle (one ambulance, cross, protected left, 12 random runs per load)\n\n| Load | Fixed: time to cross (s) | Fixed: stopped (s) | Fixed: ran a red light | Smart: time (s) | Smart: stopped (s) |\n|---:|---:|---:|---:|---:|---:|\n';
for (const e of load('emergency')) md += `| ${e.rate} | ${f1(e.fixed.time)} | ${f1(e.fixed.stop)} | ${e.fixed.risky}/${e.n} | ${f1(e.smart.time)} | ${f1(e.smart.stop)} |\n`;
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'BENCHMARKS.md'), md);
console.log('docs/BENCHMARKS.md written');
